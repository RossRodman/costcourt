from __future__ import annotations

from app.debate.models import DebateReport
from app.reports.markdown import render_markdown


def test_demo_report_reads_top_to_bottom(demo_report: DebateReport) -> None:
    md = render_markdown(demo_report)

    headings = [line for line in md.splitlines() if line.startswith("## ")]
    assert headings == [
        "## Outcome",
        "## Rulings",
        "## Missing scope raised",
        "## Debate transcript",
        "## Revised estimate",
        "## Models and token usage",
    ]
    assert md.startswith("# CostCourt report: Warehouse slab-on-grade (2,400 m²)\n")
    assert "| Change | +27,896.80 (+14.62%) |" in md
    assert "**Judge's confidence:** 82%" in md
    assert "### `02.020` Ready-mix concrete 4000 psi to 200 mm slab: Adjusted" in md
    assert "- Quantity: 420 → 504 m³" in md
    assert "- Unit rate: 165.00 → 168.00" in md
    assert "| **Grand total** |  | 190,799.27 | **218,696.07** |" in md
    assert md.endswith("Generated by CostCourt.\n")


def test_ruling_lists_the_arguments_behind_it(report: DebateReport) -> None:
    md = render_markdown(report)
    ruling = md.split("### `01.010`")[1].split("###")[0]

    assert "- Line total: 1,000.00 → 1,320.00 (+320.00)" in ruling
    assert "- Sided with: Engineer" in ruling
    assert "- **Estimator, round 1**: *Supports*: Ten cubic metres is enough." in ruling
    assert "  - Proposes quantity 12 and unit rate 110.00" in ruling
    assert "  - Answers the estimator" in ruling


def test_removed_line_and_missing_scope(report: DebateReport) -> None:
    md = render_markdown(report)

    assert "### `02.010` Formwork: Removed" in md
    assert "- Removed: 50 m² at 20.00" in md
    assert "| 02.010 | Formwork | Concrete | m² | 50 | removed | 20.00 | removed | 0.00 |" in md
    assert "- **Engineer, round 1**: *Missing scope*: Winter blankets are not priced." in md


def test_transcript_has_ids_and_reasoning(report: DebateReport) -> None:
    transcript = render_markdown(report).split("## Debate transcript")[1].split("## Revised")[0]

    assert "### Round 1" in transcript
    assert "#### Engineer" in transcript
    assert "- **Engineer**: `01.010` *Increase*: Allow waste and a winter rate." in transcript
    assert "  - Five percent waste is standard." in transcript


def test_user_text_cannot_inject_html_or_break_tables(report: DebateReport) -> None:
    md = render_markdown(report)

    assert "<script>" not in md and "<b>" not in md and "<em>" not in md
    assert "# CostCourt report: Garage &lt;script&gt;alert(1)&lt;/script&gt;" in md
    assert "Concrete &lt;b&gt;C30&lt;/b&gt; \\| slab" in md  # escaped inside a table
    assert "Leeds | UK" in md  # outside tables a pipe is harmless


def test_usage_table_with_totals(report: DebateReport) -> None:
    md = render_markdown(report)

    assert "| Estimator | 1 | claude-opus-5-5 | 1,200 | 300 | 900 |" in md
    assert "| Judge | verdict | claude-opus-5-5 | 2,000 | 500 | 0 |" in md
    assert "| **Total** |  | 2 calls | 3,200 | 800 | 900 |" in md


def test_no_rulings_and_no_recommendations(report: DebateReport) -> None:
    verdict = report.verdict.model_copy(update={"rulings": (), "recommendations": ()})
    md = render_markdown(
        report.model_copy(update={"verdict": verdict, "revised_estimate": report.estimate})
    )

    assert "The judge made no changes to the estimate." in md
    assert "### Recommendations" not in md
